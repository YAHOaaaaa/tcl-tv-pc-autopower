# Installs into an administrators-only folder and registers the "TV-Power-On" scheduled task
# (runs tv_on.ps1 as SYSTEM at boot, logon and resume), then runs it once.
# Run from an elevated PowerShell.
#
# The task runs as SYSTEM, so everything it executes or loads must be writable only by
# administrators: tv_on.ps1, config.ps1 (dot-sourced code), adb.exe and its DLLs, and the adb key.
# They are copied from this folder (and from the adb / key paths in config.ps1) into $InstallDir,
# whose ACL allows writes only to SYSTEM and Administrators. Edit config.ps1 here and run
# install.ps1 again to apply changes.
param([string]$InstallDir = (Join-Path $env:ProgramFiles 'tcl-tv-pc-autopower'))
$ErrorActionPreference = 'Stop'
if (-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
  throw 'Run this from an elevated (Administrator) PowerShell.'
}
if (-not (Test-Path "$PSScriptRoot\config.ps1")) { throw 'Create config.ps1 from config.example.ps1 first.' }
. "$PSScriptRoot\config.ps1"
if (-not (Test-Path $Adb)) { throw "adb not found: $Adb" }
if (-not (Test-Path $AdbKey)) { throw "adb key not found: $AdbKey" }

$dataDir = Join-Path $env:ProgramData 'tcl-tv-pc-autopower'
$toolsDir = Join-Path $InstallDir 'platform-tools'
New-Item -ItemType Directory -Force $InstallDir, $toolsDir, $dataDir | Out-Null

# SYSTEM and Administrators: full control. Users: read and execute only (folder contents inherit it).
$system = '*S-1-5-18'; $admins = '*S-1-5-32-544'; $users = '*S-1-5-32-545'
foreach ($d in $InstallDir, $dataDir) {
  icacls $d /inheritance:r /grant:r "${system}:(OI)(CI)F" "${admins}:(OI)(CI)F" "${users}:(OI)(CI)RX" | Out-Null
  if ($LASTEXITCODE) { throw "icacls failed on $d" }
}

Copy-Item "$PSScriptRoot\tv_on.ps1" $InstallDir -Force
# tvwatch.sh runs under the TV's sh: LF line endings
[IO.File]::WriteAllText((Join-Path $InstallDir 'tvwatch.sh'), ([IO.File]::ReadAllText("$PSScriptRoot\tvwatch.sh") -replace "`r`n", "`n"), (New-Object Text.UTF8Encoding $false))

# adb.exe plus the DLLs it loads from its own folder
$adbSrc = Split-Path $Adb
foreach ($f in 'adb.exe', 'AdbWinApi.dll', 'AdbWinUsbApi.dll') {
  if (Test-Path "$adbSrc\$f") { Copy-Item "$adbSrc\$f" $toolsDir -Force }
}

# The private key the TV already trusts: readable by SYSTEM and Administrators only
$keyDst = Join-Path $InstallDir 'adbkey'
Copy-Item $AdbKey $keyDst -Force
icacls $keyDst /inheritance:r /grant:r "${system}:F" "${admins}:F" | Out-Null
if ($LASTEXITCODE) { throw "icacls failed on $keyDst" }

# Config for the installed copy, pointing at the protected adb, key and log locations
function Q($v) { "'" + ("$v" -replace "'", "''") + "'" }
@"
# Generated by install.ps1 from $PSScriptRoot\config.ps1 - edit that file and run install.ps1 again.
`$Adb = $(Q (Join-Path $toolsDir 'adb.exe'))
`$TvAddress = $(Q $TvAddress)
`$TvMac = $(Q $TvMac)
`$AdbKey = $(Q $keyDst)
`$HdmiHardwareId = $([int]$HdmiHardwareId)
`$NoSignalDelay = $([int]$NoSignalDelay)
`$LogFile = $(Q (Join-Path $dataDir 'tv_on.log'))
"@ | Set-Content (Join-Path $InstallDir 'config.ps1') -Encoding UTF8

$script = Join-Path $InstallDir 'tv_on.ps1'
$powershell = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
$event = { param($provider, $id) "&lt;QueryList&gt;&lt;Query Id=`"0`" Path=`"System`"&gt;&lt;Select Path=`"System`"&gt;*[System[Provider[@Name='$provider'] and EventID=$id]]&lt;/Select&gt;&lt;/Query&gt;&lt;/QueryList&gt;" }
$xml = @"
<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.4" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo><Description>Wake the TCL TV over ADB and switch to the PC's HDMI input ($script)</Description></RegistrationInfo>
  <Triggers>
    <BootTrigger><Enabled>true</Enabled></BootTrigger>
    <LogonTrigger><Enabled>true</Enabled></LogonTrigger>
    <EventTrigger><Enabled>true</Enabled><Subscription>$(& $event 'Microsoft-Windows-Power-Troubleshooter' 1)</Subscription></EventTrigger>
    <EventTrigger><Enabled>true</Enabled><Subscription>$(& $event 'Microsoft-Windows-Kernel-General' 12)</Subscription></EventTrigger>
  </Triggers>
  <Principals><Principal id="Author"><UserId>S-1-5-18</UserId><RunLevel>HighestAvailable</RunLevel></Principal></Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <ExecutionTimeLimit>PT5M</ExecutionTimeLimit>
    <Enabled>true</Enabled>
  </Settings>
  <Actions Context="Author">
    <Exec><Command>$powershell</Command><Arguments>-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "$script"</Arguments></Exec>
  </Actions>
</Task>
"@
$tmp = Join-Path $env:TEMP 'TV-Power-On.xml'
[IO.File]::WriteAllText($tmp, $xml, [Text.Encoding]::Unicode)
schtasks /create /tn 'TV-Power-On' /xml $tmp /f
Remove-Item $tmp
"Installed to $InstallDir (log: $dataDir\tv_on.log)"
schtasks /run /tn 'TV-Power-On'
